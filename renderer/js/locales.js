const DEFAULT_LANG = 'en-US';
let currentLangCode = DEFAULT_LANG;

function runtimeLang() {
  try { return navigator.language || DEFAULT_LANG; } catch { return DEFAULT_LANG; }
}

function resolveMap(code) {
  const map = I18N[code];
  if (map) return map;
  const base = String(code).split('-')[0];
  for (const key of Object.keys(I18N)) {
    if (String(key).startsWith(base)) return I18N[key];
  }
  return I18N[enDefault()];
}
function enDefault() { return DEFAULT_LANG; }

function t(key, ...args) {
  const map = resolveMap(currentLangCode);
  let str = map[key];
  if (str === undefined) str = I18N[DEFAULT_LANG][key];
  if (str === undefined) return key;
  if (args.length) {
    let i = 0;
    str = str.replace(/%s/g, () => (i < args.length ? args[i++] : '%s'));
  }
  return str;
}

function applyI18n() {
  if (currentLangCode === 'ar-SA' || currentLangCode === 'zh-CN' || currentLangCode === 'zh-TW' || currentLangCode === 'ja-JP' || currentLangCode === 'ko-KR') {
    document.documentElement.dir = 'ltr';
  } else {
    document.documentElement.dir = 'ltr';
  }
  document.querySelectorAll('[data-i18n]').forEach((el) => {
    const key = el.getAttribute('data-i18n');
    const text = t(key);
    if (text && text !== key) {
      if (el.tagName === 'INPUT') el.placeholder = text;
      else el.textContent = text;
    }
  });
}

function langDisplay(code) {
  const item = LANGUAGES.find((l) => l.code === code);
  return item ? item.native || item.name : code;
}

// German-style/other systems use HH:mm; keep 12h toggle off -> use local format.
function fmtTime(d, withSeconds = false) {
  const h = d.getHours();
  const m = String(d.getMinutes()).padStart(2, '0');
  const s = withSeconds ? ':' + String(d.getSeconds()).padStart(2, '0') : '';
  return `${h}:${m}${s}`;
}

// Um currentLangCode invalido (config.json editado a mao) fazia
// toLocaleDateString lancar RangeError dentro do render e derrubar a tela.
function safeLang() {
  try {
    const d = new Date();
    if (currentLangCode) d.toLocaleDateString(currentLangCode);
    return currentLangCode;
  } catch (e) {
    return DEFAULT_LANG;
  }
}

function fmtDate(d) {
  const optsDate = { weekday: 'long', month: 'long', day: 'numeric' };
  try {
    return d.toLocaleDateString(safeLang(), optsDate);
  } catch (e) {
    return d.toLocaleDateString(DEFAULT_LANG, optsDate);
  }
}
function fmtDateShort(d) {
  try {
    return d.toLocaleDateString(safeLang(), { year: 'numeric', month: 'numeric', day: 'numeric' });
  } catch (e) {
    return d.toLocaleDateString(DEFAULT_LANG, { year: 'numeric', month: 'numeric', day: 'numeric' });
  }
}